import {
  hasSubstantiveEnrichment,
  type EnrichmentLookup,
  type LibraryEnrichment,
} from './enrichmentParse'
import { libraryData } from './libraryData'
import { TIMELINE_LABEL_ALIASES } from './timelineLabelAliases.generated'
import timelineEnrichmentsJson from './generated/timelineEnrichments.generated.json'

export type { LibraryEnrichment, EnrichmentLookup }
export { hasSubstantiveEnrichment }

/**
 * Maps library downloadUrl → referenceId for cross-linking timeline events to library records.
 * Used by UI components to show "Also in Library →" badges when a timeline SourceUrl
 * matches a library document.
 */
export const timelineToLibraryRef: Record<string, string> = Object.fromEntries(
  libraryData.filter((item) => item.downloadUrl).map((item) => [item.downloadUrl, item.referenceId])
)

// The merged lookup over ALL timeline enrichment generations — the live
// directory and all three archive tiers — precomputed at build time by
// the timeline-enrichment generator (27 Sep 2026). Reading the 40 raw
// markdown files here (34.2 MB) made this module an 86 MB app chunk; the merged
// result is 338 entries, 1.1 MB. The merge-all semantics are unchanged: the
// archive tiers must stay in (excluding them once lost 6 live, non-deprecated
// rows — Brazil:ITI, G7:G7 CEG, Germany:BSI, Hong Kong:HKMA, Malaysia:NACSA,
// Singapore:CSA/GovTech/IMDA). timelineEnrichments.generated.test.ts proves the
// file equals mergeEnrichmentFiles over the raw files, key for key.
export const timelineEnrichments: EnrichmentLookup = timelineEnrichmentsJson as EnrichmentLookup

/**
 * Build the enrichment lookup key for a timeline document row.
 * Matches the key format generated by the enrichment script:
 * "{countryName}:{org} — {title}"
 */
export function getTimelineEnrichmentKey(countryName: string, org: string, title: string): string {
  return `${countryName}:${org} — ${title}`
}

const libraryById = new Map(libraryData.map((item) => [item.referenceId, item]))
// A superseded Library id resolves to the record that replaced it.
for (const item of libraryData)
  for (const prior of item.priorRevisions ?? [])
    if (!libraryById.has(prior.referenceId)) libraryById.set(prior.referenceId, item)

export interface TimelineLibraryLink {
  referenceId: string
  title: string
}

/**
 * The Library records a timeline event points to: its curated `library_refs`
 * first, then a Library document whose download URL is the event's source URL.
 * Ids with no Library record (retired with no successor) are left out.
 */
export function timelineLibraryLinks(event: {
  libraryRefs?: string[]
  sourceUrl?: string
}): TimelineLibraryLink[] {
  const ids = [
    ...(event.libraryRefs ?? []),
    ...(event.sourceUrl && timelineToLibraryRef[event.sourceUrl]
      ? [timelineToLibraryRef[event.sourceUrl]]
      : []),
  ]
  const out = new Map<string, TimelineLibraryLink>()
  for (const id of ids) {
    const item = libraryById.get(id)
    if (item && !out.has(item.referenceId))
      out.set(item.referenceId, { referenceId: item.referenceId, title: item.documentTitle })
  }
  return [...out.values()]
}

/**
 * The enrichment-lookup key a timeline row's enrichment lives under: its
 * current label, else an earlier label of the same event_id; undefined when
 * the row has no enrichment.
 */
export function getTimelineEnrichmentKeyFor(
  eventId: string | undefined,
  countryName: string,
  org: string,
  title: string
): string | undefined {
  const direct = getTimelineEnrichmentKey(countryName, org, title)
  // eslint-disable-next-line security/detect-object-injection -- lookup by built key
  if (timelineEnrichments[direct]) return direct
  if (!eventId) return undefined
  // eslint-disable-next-line security/detect-object-injection
  return (TIMELINE_LABEL_ALIASES[eventId] ?? []).find((label) => !!timelineEnrichments[label])
}

/**
 * The enrichment for a timeline row: by its current label first, then by any
 * label the same event_id carried in an earlier CSV generation. Enrichment
 * sections are keyed by label, so a title edit used to orphan a row's
 * enrichment (timeline remediation r2 W-B).
 */
export function getTimelineEnrichment(
  eventId: string | undefined,
  countryName: string,
  org: string,
  title: string
): LibraryEnrichment | undefined {
  const direct = timelineEnrichments[getTimelineEnrichmentKey(countryName, org, title)]
  if (direct || !eventId) return direct
  // eslint-disable-next-line security/detect-object-injection
  for (const label of TIMELINE_LABEL_ALIASES[eventId] ?? []) {
    // eslint-disable-next-line security/detect-object-injection
    const hit = timelineEnrichments[label]
    if (hit) return hit
  }
  return undefined
}
