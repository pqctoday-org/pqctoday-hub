export const isBrainpoolSet = (s: { trad: string }): boolean => s.trad.includes('brainpool')

export const compositeSigSet = (ckp: number): CompositeSigSet | undefined =>
  COMPOSITE_SIG_SETS.find((s) => s.ckp === ckp)

export const compositeKemSet = (ckp: number): CompositeKemSet | undefined =>
  COMPOSITE_KEM_SETS.find((s) => s.ckp === ckp)

/** The label bytes of a composite KEM set. */
export const kemLabelBytes = (s: CompositeKemSet): Uint8Array =>
  new Uint8Array((s.labelHex.match(/.{2}/g) ?? []).map((h) => parseInt(h, 16)))

/** The composite signature prefix, draft-ietf-lamps-pq-composite-sigs-19 §2.2:
 * the ASCII string "CompositeAlgorithmSignatures2025". */
export const COMPOSITE_SIG_PREFIX_HEX =
  '436f6d706f73697465416c676f726974686d5369676e61747572657332303235'

/** Short display name, e.g. "ML-DSA-65 + ECDSA-P256". */
export const compositeDisplayName = (s: { ml: string; trad: string }): string =>
  `${s.ml} + ${s.trad}`
