/**
 * compositeParams.ts — the 30 PKCS#11 v3.3 composite parameter sets, one row
 * each: the CKP_* value and name, the IETF draft algorithm it names, its OID
 * and label, its components and its sizes. Every v3.3 surface in the hub (the
 * Learn track, the Build test bench, the Inspect display, the v3.3 draft
 * checks) reads this one table.
 *
 * Sources (all checked 2026-10-21):
 *  - CKP_* names, values and header lines: OASIS PKCS 11 TC working tree,
 *    github.com/oasis-tcs/pkcs11 commit 9ef73f9, working/headers/pkcs11t.h
 *    (sha256 765a28ac…f70e). PKCS#11 v3.3 is an unpublished working draft;
 *    these codepoints are marked approved there.
 *  - OIDs, labels, components, pre-hash and sizes:
 *    draft-ietf-lamps-pq-composite-sigs-19 (§6, Appendix A; sha256
 *    b4ee0441…ec83) and draft-ietf-lamps-pq-composite-kem-23 (§6, Appendix A
 *    Table 3; sha256 aaaffdf5…26b8). Sizes marked `…IsMax` are the drafts'
 *    maximum sizes (RSA and ECDSA encodings vary by a few bytes).
 *
 * The CKP_ order in the header and the algorithm order in both drafts are the
 * same; compositeParams.test.ts checks every row's CKP_ name against its
 * draft name token by token, so a shifted row fails.
 */

export interface CompositeSigSet {
  ckp: number
  ckpName: string
  headerLine: number
  draftName: string
  oid: string
  /** The draft's signature label (ASCII), also the ML-DSA context string. */
  label: string
  ml: 'ML-DSA-44' | 'ML-DSA-65' | 'ML-DSA-87'
  trad: string
  preHash: string
  mlPublicKeyBytes: number
  mlSignatureBytes: number
  publicKeyBytes: number
  publicKeyIsMax: boolean
  privateKeyBytes: number
  privateKeyIsMax: boolean
  signatureBytes: number
  signatureIsMax: boolean
}

export interface CompositeKemSet {
  ckp: number
  ckpName: string
  headerLine: number
  draftName: string
  oid: string
  /** The draft's KEM combiner label, as hex of its bytes. */
  labelHex: string
  ml: 'ML-KEM-768' | 'ML-KEM-1024'
  trad: string
  mlPublicKeyBytes: number
  mlCiphertextBytes: number
  publicKeyBytes: number
  publicKeyIsMax: boolean
  privateKeyBytes: number
  privateKeyIsMax: boolean
  ciphertextBytes: number
  sharedSecretBytes: number
}

