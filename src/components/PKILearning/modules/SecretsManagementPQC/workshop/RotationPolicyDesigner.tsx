import React, { useState } from 'react'
import { AlertTriangle, CheckCircle, Download } from 'lucide-react'
import { ROTATION_POLICIES } from '../data/secretsConstants'
import { FilterDropdown } from '@/components/common/FilterDropdown'
import { Button } from '@/components/ui/button'

interface PolicyRow {
  id: string
  secretType: string
  currentTtl: string
  pqcTtl: string
  maxTtl: string | undefined
  renewalWindow: string
  complianceFramework: string
  automationTool: string
  pqcConsideration: string
}

// TTL options for dropdowns
const TTL_OPTIONS = [
  '1 hour',
  '8 hours',
  '1 day',
  '7 days',
  '30 days',
  '60 days',
  '90 days',
  '180 days',
  '1 year',
  '2 years',
]

// Single-duration sample conversion. Compound or missing lifetimes are not comparable.
function parseTtlDays(ttl: string | undefined): number | null {
  const parts = ttl?.trim().toLowerCase().split(/\s+/)
  if (!parts || parts.length !== 2) return null
  const [quantityText, rawUnit] = parts
  const numericParts = quantityText.split('.')
  if (numericParts.length > 2 || numericParts.some((part) => !/^\d+$/.test(part))) return null
  const quantity = Number(quantityText)
  if (!Number.isFinite(quantity)) return null
  const unit = rawUnit.endsWith('s') ? rawUnit.slice(0, -1) : rawUnit
  switch (unit) {
    case 'hour':
      return quantity / 24
    case 'day':
      return quantity
    case 'week':
      return quantity * 7
    case 'month':
      return quantity * 30
    case 'year':
      return quantity * 365
    default:
      return null
  }
}

const generateYaml = (rows: PolicyRow[]): string => {
  const lines: string[] = [
    '# Illustrative Secrets Rotation Policy Draft — unvalidated configuration',
    '# Sample TTL comparisons do not validate the requirements or provider configuration below.',
    '# Generated by PQC Today — Secrets Management Module',
    `# Date: ${new Date().toISOString().split('T')[0]}`,
    '',
    'rotation_policies:',
  ]

  rows.forEach((row) => {
    const key = row.id.replace(/-rotation$/, '').replace(/-/g, '_')
    lines.push(`  ${key}:`)
    lines.push(`    secret_type: "${row.secretType}"`)
    lines.push(`    ttl: "${row.currentTtl}"`)
    lines.push(`    renewal_window: "${row.renewalWindow}"`)
    lines.push(`    compliance_framework: "${row.complianceFramework}"`)
    lines.push(`    automation_tool: "${row.automationTool}"`)
    lines.push(`    # PQC: ${row.pqcConsideration.substring(0, 80)}...`)
    lines.push('')
  })

  lines.push('pqc_requirements:')
  lines.push('  vault_version: ">=1.18.0"')
  lines.push('  kek_algorithm: "ML-KEM-768"')
  lines.push('  signing_algorithm: "ML-DSA-65"')
  lines.push('  tls_hybrid: "X25519+ML-KEM-768"')

  return lines.join('\n')
}

export const RotationPolicyDesigner: React.FC = () => {
  const [policyRows, setPolicyRows] = useState<PolicyRow[]>(
    ROTATION_POLICIES.map((p) => ({
      id: p.id,
      secretType: p.secretType,
      currentTtl: p.ttl,
      pqcTtl: p.ttl,
      maxTtl: p.maxTTL,
      renewalWindow: p.renewalWindow,
      complianceFramework: p.complianceFramework,
      automationTool: p.automationTool,
      pqcConsideration: p.pqcConsideration,
    }))
  )
  const [showYaml, setShowYaml] = useState(false)

  const updateTtl = (id: string, ttl: string) => {
    setPolicyRows((prev) => prev.map((r) => (r.id === id ? { ...r, currentTtl: ttl } : r)))
  }

  const comparedRows = policyRows.map((row) => {
    const currentDays = parseTtlDays(row.currentTtl)
    const maxDays = parseTtlDays(row.maxTtl)
    const comparison =
      currentDays === null || maxDays === null
        ? 'unknown'
        : currentDays > maxDays
          ? 'exceeds'
          : 'within'
    return { ...row, comparison }
  })
  const warningRows = comparedRows.filter((row) => row.comparison === 'exceeds')
  const unknownRows = comparedRows.filter((row) => row.comparison === 'unknown')

  const yamlContent = generateYaml(policyRows)

  return (
    <div className="space-y-6">
      {/* Instructions */}
      <div className="bg-muted/50 rounded-lg p-4 border border-border text-xs text-muted-foreground">
        Compare TTL selections with the illustrative policy limits shown in this sample. These are
        not universal PQC requirements or an assessment of cryptographic security. Conversion uses
        24 hours per day, 30 days per month and 365 days per year as sample approximations. Compound
        or incomparable lifetimes remain not assessed. The YAML is an unvalidated draft; a TTL
        comparison does not validate its provider requirements or configuration.
      </div>

      {/* Policy Table */}
      <div className="overflow-x-auto">
        <table className="w-full text-xs">
          <thead>
            <tr className="border-b border-border">
              <th className="text-left py-3 px-2 text-muted-foreground font-medium min-w-[90px] sm:min-w-[140px]">
                Secret Type
              </th>
              <th className="text-left py-3 px-2 text-muted-foreground font-medium min-w-[100px] sm:min-w-[120px]">
                Your TTL
              </th>
              <th className="text-left py-3 px-2 text-muted-foreground font-medium hidden sm:table-cell">
                Sample Max TTL
              </th>
              <th className="text-left py-3 px-2 text-muted-foreground font-medium hidden md:table-cell">
                Automation
              </th>
              <th className="text-left py-3 px-2 text-muted-foreground font-medium hidden lg:table-cell">
                Compliance
              </th>
              <th className="text-center py-3 px-2 text-muted-foreground font-medium">Status</th>
            </tr>
          </thead>
          <tbody>
            {comparedRows.map((row) => {
              const isOver = row.comparison === 'exceeds'

              return (
                <tr
                  key={row.id}
                  className={`border-b border-border/50 ${isOver ? 'bg-status-warning/5' : ''}`}
                >
                  <td className="py-3 px-2 font-medium text-foreground">{row.secretType}</td>
                  <td className="py-3 px-2">
                    <div className="w-[100px] sm:w-auto">
                      <FilterDropdown
                        noContainer
                        ariaLabel={`TTL for ${row.secretType}`}
                        selectedId={row.currentTtl}
                        onSelect={(id) => updateTtl(row.id, id)}
                        items={TTL_OPTIONS.map((opt) => ({ id: opt, label: opt }))}
                        className="max-w-[120px]"
                      />
                    </div>
                    <p className="mt-1 text-[10px] text-muted-foreground">
                      Selected: {row.currentTtl}
                    </p>
                    <p className="mt-1 text-[10px] text-muted-foreground sm:hidden">
                      Sample limit: {row.maxTtl || 'Not specified'}
                    </p>
                  </td>
                  <td className="py-3 px-2 text-muted-foreground hidden sm:table-cell">
                    {row.maxTtl || 'Not specified'}
                  </td>
                  <td className="py-3 px-2 text-muted-foreground hidden md:table-cell">
                    <span className="line-clamp-1">{row.automationTool}</span>
                  </td>
                  <td className="py-3 px-2 text-muted-foreground hidden lg:table-cell">
                    <span className="line-clamp-1">{row.complianceFramework}</span>
                  </td>
                  <td className="py-3 px-2 text-center">
                    {row.comparison === 'unknown' ? (
                      <span className="text-muted-foreground">Comparison not assessed</span>
                    ) : isOver ? (
                      <span className="text-status-warning">
                        <AlertTriangle size={14} className="inline-block mr-1" />
                        Exceeds sample limit
                      </span>
                    ) : (
                      <span className="text-status-success">
                        <CheckCircle size={14} className="inline-block mr-1" />
                        Within sample limit
                      </span>
                    )}
                  </td>
                </tr>
              )
            })}
          </tbody>
        </table>
      </div>

      {/* Warnings */}
      {warningRows.length > 0 && (
        <div className="bg-status-warning/10 border border-status-warning/30 rounded-lg p-4 space-y-2">
          <div className="flex items-center gap-2 mb-2">
            <AlertTriangle size={16} className="text-status-warning" />
            <span className="text-sm font-bold text-status-warning">
              TTL Exceeds Sample Policy Limit
            </span>
          </div>
          {warningRows.map((row) => {
            return (
              <div key={row.id} className="text-xs text-muted-foreground">
                <strong className="text-foreground">{row.secretType}</strong>: Selected{' '}
                <span className="text-status-warning font-mono">{row.currentTtl}</span> exceeds the
                sample limit <span className="font-mono">{row.maxTtl}</span>.{' '}
                {row.pqcConsideration.substring(0, 120)}
              </div>
            )
          })}
        </div>
      )}

      {unknownRows.length > 0 && (
        <div className="bg-muted/50 rounded-lg p-4 border border-border text-xs text-muted-foreground">
          {unknownRows.map((row) => (
            <p key={row.id}>
              <strong>{row.secretType}: comparison not assessed.</strong>{' '}
              {row.id === 'oauth-token-rotation'
                ? 'This sample mixes token and signing-key lifetimes; compare each object separately.'
                : 'A single comparable current duration and sample limit are not available.'}
            </p>
          ))}
        </div>
      )}
      {/* PQC Considerations Table */}
      <div className="bg-muted/50 rounded-lg p-4 border border-border">
        <div className="text-sm font-bold text-foreground mb-3">PQC Rotation Considerations</div>
        <div className="space-y-2">
          {policyRows.map((row) => (
            <div key={row.id} className="flex items-start gap-2">
              <span className="text-primary shrink-0 mt-0.5 text-xs">&#8227;</span>
              <div className="text-[10px] text-muted-foreground">
                <strong className="text-foreground">{row.secretType}</strong>:{' '}
                {row.pqcConsideration}
              </div>
            </div>
          ))}
        </div>
      </div>

      {/* Generate YAML button */}
      <div className="flex flex-wrap gap-3">
        <Button
          variant="gradient"
          onClick={() => setShowYaml(!showYaml)}
          className="flex items-center gap-2 px-4 py-2 font-bold rounded-lg transition-colors text-sm"
        >
          <Download size={14} />
          {showYaml ? 'Hide' : 'View'} Unvalidated YAML Draft
        </Button>
        {warningRows.length === 0 && unknownRows.length === 0 && (
          <div className="flex items-center gap-2 text-sm text-status-success">
            <CheckCircle size={16} />
            All assessed TTLs within sample limits
          </div>
        )}
      </div>

      {showYaml && (
        <div>
          <div className="text-sm font-bold text-foreground mb-2">
            Illustrative Rotation Policy Draft — Not Validated
          </div>
          <div className="bg-muted font-mono text-xs rounded-lg p-4 overflow-x-auto border border-border whitespace-pre text-foreground/90 max-h-96 overflow-y-auto">
            {yamlContent}
          </div>
        </div>
      )}
    </div>
  )
}
