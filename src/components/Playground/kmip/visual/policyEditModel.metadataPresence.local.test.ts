import { readFileSync } from 'node:fs'
import { beforeAll, describe, expect, it } from 'vitest'
import { normalized, serialize, toEditable } from './policyEditModel'

// Exact source retained from the native built-in → Add algorithm_denylist failure.
const failedNativeSource = `# built-in-permissive — generated by the CACP visual editor
schema_version: 1

metadata:
  name: built-in-permissive
  effective: "always"

rules:

  - type: algorithm_denylist
    ops: [Create, Sign]
    algorithms: [RSA-PKCS1-v1_5, 3DES]
    reason: "Weak/legacy algorithms banned by policy"
`

interface BgModule {
  __wbg_set_wasm: (exports: unknown) => void
  KmipPlayground: new (slot?: number) => {
    load_policy: (yaml: string) => string
    policy_status: () => string
    free: () => void
  }
}
let bg: BgModule
beforeAll(async () => {
  bg = (await import('@/wasm/kmip/pqctoday_kmip_wasm_bg.js')) as unknown as BgModule
  const bytes = readFileSync('src/wasm/kmip/pqctoday_kmip_wasm_bg.wasm')
  const { instance } = await WebAssembly.instantiate(bytes, {
    './pqctoday_kmip_wasm_bg.js': bg as unknown as WebAssembly.ModuleImports,
  })
  bg.__wbg_set_wasm(instance.exports)
  ;(instance.exports as unknown as { __wbindgen_start: () => void }).__wbindgen_start()
}, 30_000)

// Existing engine contract: each instance needs its own sample token slot.
let nextSlot = 10
function load(yaml: string) {
  const pg = new bg.KmipPlayground(nextSlot++)
  try {
    const result = JSON.parse(pg.load_policy(yaml)) as { ok: boolean; error?: string }
    const status = JSON.parse(pg.policy_status()) as { rules?: number; name?: string }
    return { result, status }
  } finally {
    pg.free()
  }
}

describe('existing required metadata string presence', () => {
  it('preserves empty strings instead of omitting required description and authority', () => {
    const policy = toEditable(failedNativeSource)
    const yaml = serialize(policy)
    expect(yaml).toContain('  description: ""')
    expect(yaml).toContain('  authority: ""')
    const roundTrip = toEditable(yaml)
    expect(roundTrip.metadata).toEqual(policy.metadata)
    expect(normalized(roundTrip)).toEqual(normalized(policy))
    expect(roundTrip.rules).toHaveLength(policy.rules.length)
  })
  it('accepts the exact native Add-rule source after string-preserving serialization in the actual bundled loader', () => {
    const before = load(failedNativeSource)
    expect(before.result.ok).toBe(false)
    expect(before.result.error).toContain('missing field `description`')
    const after = load(serialize(toEditable(failedNativeSource)))
    expect(after.result.ok, after.result.error).toBe(true)
    expect(after.status.rules).toBe(1)
    expect(after.status.name).toBe('built-in-permissive')
  })
  it('preserves nonempty multiline text and authority, then an explicit user clearing of both fields', () => {
    const policy = toEditable(failedNativeSource)
    policy.metadata.description = 'First line, sample only\nSecond line — Montréal'
    policy.metadata.authority = 'Learner sample, not an endorsement'
    const roundTrip = toEditable(serialize(policy))
    expect(roundTrip.metadata).toEqual(policy.metadata)
    roundTrip.metadata.description = ''
    roundTrip.metadata.authority = ''
    const cleared = serialize(roundTrip)
    expect(toEditable(cleared).metadata.description).toBe('')
    expect(toEditable(cleared).metadata.authority).toBe('')
    expect(cleared).not.toContain('Montréal')
    expect(load(cleared).result.ok).toBe(true)
  })
  it('does not fabricate a valid effective time to bypass a real loader failure', () => {
    const policy = toEditable(failedNativeSource)
    policy.metadata.effective = 'not-a-date'
    const yaml = serialize(policy)
    expect(yaml).toContain('not-a-date')
    const { result } = load(yaml)
    expect(result.ok).toBe(false)
    expect(result.error).toContain('metadata.effective')
  })
})
