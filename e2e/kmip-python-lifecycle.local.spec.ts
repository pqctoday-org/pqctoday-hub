import { text } from 'node:stream/consumers'
import { expect, test } from './fixtures/blockAnalytics'

for (const width of [1280, 390]) {
  test(`the KMIP Python workbench enforces activation on the signing key at ${width}px`, async ({
    page,
  }) => {
    test.setTimeout(120_000)
    await page.setViewportSize({ width, height: 900 })
    await page.addInitScript(() => {
      localStorage.setItem(
        'pqc-disclaimer-storage',
        JSON.stringify({ state: { acknowledgedMajorVersion: 99 }, version: 0 })
      )
      localStorage.setItem(
        'pqc-version-storage',
        JSON.stringify({ state: { lastSeenVersion: '99.0.0' }, version: 0 })
      )
      localStorage.setItem('pqc-tour-completed', 'true')
    })
    await page.goto('/playground/cacp')
    await page.getByRole('button', { name: 'Open the KMIP Python workbench' }).click()
    await expect(page).toHaveURL(/tab=dev/)
    await page.getByRole('tab', { name: 'Code', exact: true }).click()
    await page.getByText('Practice activating a signing key', { exact: true }).click()
    await expect(page.getByText(/change priv_create to pub_create/i)).toBeVisible()

    const editor = page.locator('.monaco-editor .view-lines')
    await expect(editor).toBeVisible({ timeout: 30_000 })
    const run = page.getByRole('button', { name: 'Run', exact: true })
    const receipt = page.getByRole('region', { name: 'Recorded sample attempt' })
    const details = receipt.locator('details')
    const showAttemptOutput = async () => {
      if ((await details.getAttribute('open')) === null) {
        await details.locator('summary').click()
      }
      return details.locator('pre').last()
    }
    const runOriginal = async () => {
      await expect(run).toBeEnabled()
      await run.click()
      await expect(receipt).toContainText('Required generated sample steps completed.', {
        timeout: 45_000,
      })
      const output = await showAttemptOutput()
      await expect(output).toContainText(/expect-deny: refused/)
      await expect(output).toContainText('signature 3309 bytes')
    }
    await runOriginal()

    const [file] = await Promise.all([
      page.waitForEvent('download'),
      page.getByRole('button', { name: 'Export .py' }).click(),
    ])
    const exported = await text(await file.createReadStream())
    const original = exported.slice(exported.indexOf('"""Generated by'))
    const activate = "c.submit('Activate', leaf('UniqueIdentifier', 'Identifier', priv_create))"
    expect(original).toContain(activate)
    await page.getByRole('button', { name: 'Edit as custom script' }).click()
    await editor.click()
    const activateLine = original.split('\n').findIndex((line) => line.includes(activate))
    expect(activateLine).toBeGreaterThan(0)
    await page.keyboard.press('ControlOrMeta+Home')
    for (let i = 0; i < activateLine; i++) await page.keyboard.press('ArrowDown')
    await page.keyboard.press('End')
    await page.keyboard.press('ArrowLeft')
    await page.keyboard.press('ArrowLeft')
    for (let i = 0; i < 'priv_create'.length; i++) await page.keyboard.press('Shift+ArrowLeft')
    await page.keyboard.insertText('pub_create')
    await expect(receipt).toContainText('Inputs changed')
    await page.getByText('Practice activating a signing key', { exact: true }).click()
    await run.click()
    await expect(receipt).toContainText('Sample attempt failed.', { timeout: 45_000 })
    await expect(receipt).toContainText('custom code')
    const output = await showAttemptOutput()
    await expect(output).toContainText('###STEP activate ok###')
    await expect(output).toContainText('###STEP sign error###')
    await expect(output).toContainText(
      /###STEP sign error### RuntimeError: KMIP WrongKeyLifecycleState \(0x00000043\)/
    )
    const publicId = (await output.textContent())?.match(/pub=(urn:pqctoday:obj:[a-f0-9-]+)/)?.[1]
    expect(publicId).toBeTruthy()
    await expect(output).toContainText(`activated ${publicId}`)

    await page.getByRole('button', { name: 'Discard edits, resync' }).click()
    await runOriginal()
  })
}
