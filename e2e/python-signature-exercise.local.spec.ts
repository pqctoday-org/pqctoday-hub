import { text } from 'node:stream/consumers'
import { PYTHON_SIGNATURE_EXERCISE_PATH } from '../src/data/pythonWorkbench'
import { test, expect } from './fixtures/blockAnalytics'

for (const width of [1280, 390]) {
  for (const entry of ['developer lesson', 'Developer home', 'Explore', 'Developer navigation']) {
    test(`the ${entry} reaches an editable PKCS#11 Python verification at ${width}px`, async ({
      page,
    }) => {
      test.setTimeout(120_000)
      await page.setViewportSize({ width, height: 900 })
      await page.addInitScript(() => {
        localStorage.setItem(
          'pqc-disclaimer-storage',
          JSON.stringify({ state: { acknowledgedMajorVersion: 99 }, version: 0 })
        )
        localStorage.setItem(
          'pqc-version-storage',
          JSON.stringify({ state: { lastSeenVersion: '99.0.0' }, version: 0 })
        )
        localStorage.setItem('pqc-tour-completed', 'true')
      })
      if (entry === 'Developer home') {
        await page.goto('/')
        await page.getByRole('button', { name: /^Developer \/ Engineer/ }).press('Enter')
        await page.getByRole('link', { name: 'Run Python in your browser' }).press('Enter')
      } else if (entry === 'Developer navigation') {
        await page.goto('/')
        await page.getByRole('button', { name: /^Developer \/ Engineer/ }).press('Enter')
        if (width === 390) {
          await page
            .getByRole('navigation', { name: 'Main navigation', exact: true })
            .getByRole('button', { name: 'Practice', exact: true })
            .press('Enter')
          await page
            .getByTestId('mobile-group-panel-practice')
            .getByRole('link', { name: 'Python signature lab' })
            .press('Enter')
        } else {
          const nav = page.getByRole('navigation', { name: 'Primary navigation' })
          const expand = nav.getByRole('button', { name: /^Show Practice/ })
          if (await expand.count()) await expand.press('Enter')
          await nav.getByRole('link', { name: 'Python signature lab' }).press('Enter')
        }
      } else if (entry === 'Explore') {
        await page.goto('/explore')
        await page
          .getByRole('link', { name: 'Edit and run a Python signature check' })
          .press('Enter')
      } else {
        await page.goto('/learn/crypto-dev-apis?tab=workshop&step=1&sv=2')
        await page.getByRole('button', { name: 'Compare Mode' }).click()
        const selectPython = page.getByRole('button', { name: 'Select Python for comparison' })
        await selectPython.press('Space')
        await expect(selectPython).toHaveAttribute('aria-pressed', 'true')
        await selectPython.press('Space')
        await expect(selectPython).toHaveAttribute('aria-pressed', 'false')
        await page.getByRole('button', { name: 'Expand Python', exact: true }).click()
        await page
          .getByRole('link', { name: 'Edit and test Python signature verification' })
          .click()
      }
      await expect(page).toHaveURL(
        (url) => url.pathname + url.search === PYTHON_SIGNATURE_EXERCISE_PATH
      )
      await expect(page.getByLabel('Pipeline name')).toHaveValue('ML-DSA sign and verify')
      await expect(page.getByText('Check which bytes a signature covers')).toBeVisible()

      const editor = page.locator('.monaco-editor')
      await expect(editor).toBeVisible({ timeout: 25_000 })
      const run = page.getByRole('button', { name: 'Run', exact: true })
      await run.click()
      await expect(
        page.getByText(/signed the sample message and verified the signature/)
      ).toBeVisible({
        timeout: 40_000,
      })
      const [file] = await Promise.all([
        page.waitForEvent('download'),
        page.getByRole('button', { name: 'Export .py' }).click(),
      ])
      const original = await text(await file.createReadStream())
      const code = original.slice(original.indexOf('"""Generated by')).split('\n')
      const verifyLine = code.findIndex((line) => line.includes('s.verify('))
      expect(verifyLine).toBeGreaterThan(0)
      const originalLine = code[verifyLine].trimStart()
      expect(originalLine).toContain(', pipeline_input,')
      const changedLine = originalLine.replace(', pipeline_input,', ", b'changed message',")
      const replaceVerification = async (line: string) => {
        await editor.locator('.view-lines').click()
        await page.keyboard.press('ControlOrMeta+Home')
        for (let i = 0; i < verifyLine; i++) await page.keyboard.press('ArrowDown')
        await page.keyboard.press('End')
        await page.keyboard.press('Shift+Home')
        await page.keyboard.insertText(line)
      }
      await replaceVerification(changedLine)
      await run.click()
      await expect(page.locator('pre[aria-live=polite]')).toContainText('verify · FAIL', {
        timeout: 40_000,
      })
      await replaceVerification(originalLine)
      await run.click()
      await expect(
        page.getByText(/signed the sample message and verified the signature/)
      ).toBeVisible({
        timeout: 40_000,
      })
      if (entry === 'Developer home') {
        await page.goBack()
        await expect(page).toHaveURL(/\/$/)
        const link = page.getByRole('link', { name: 'Run Python in your browser' })
        await expect(link).toBeVisible()
        await page.reload()
        await expect(link).toBeVisible()
      }
    })
  }
}
