/**
 * gen-landing-counts — pre-compute the Landing page hero-counter numbers at
 * build time, from the same canonical CSVs the real async loaders read
 * (src/data/pqc_complete_algorithm_reference_*.csv, timeline_*.csv,
 * library_*.csv — latest date wins). Emits src/data/landingCounts.generated.ts.
 * Run as a prebuild step so the hero counters render a real number on first
 * paint instead of the literal string '...' while LandingView's useEffect
 * fetches the full datasets (which it still does, and still needs to, for
 * the next-CNSA-deadline / latest-RFC derivations those same loads power —
 * this script only seeds the INITIAL state, the real async load still runs
 * and self-corrects the count if it's ever off).
 *
 *   node scripts/gen-landing-counts.mjs           # (re)generate
 *   node scripts/gen-landing-counts.mjs --check   # exit 1 if stale (CI gate)
 *
 * These are deliberately ESTIMATES, not a byte-exact mirror of each loader's
 * full filtering logic:
 *   - algorithms: total row count. The real loader additionally drops ~2
 *     hand-classified "placeholder" rows (NGCC-BC/NGCC-CH) via a bespoke
 *     lookup table in pqcAlgorithmsData.ts — replicating that table here
 *     would be a second copy of hand-maintained classification data, exactly
 *     the kind of drift risk this codebase has hit before. Left as a ~1-2%
 *     overcount that self-corrects within the same render pass.
 *   - timeline / library: active rows only (status NOT deprecated/obsolete —
 *     the standard DS01 self-containment filter), matching filterActive().
 *     The real loaders drop a further handful of rows with missing
 *     Country/unparseable dates (timeline) — not replicated here either, for
 *     the same reason.
 * A hero counter briefly showing 261 before the real load confirms 258 is a
 * normal, unremarkable web pattern; a hero counter showing the literal text
 * '...' is the actual defect this script exists to fix.
 */
import { readFileSync, writeFileSync, readdirSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'
import Papa from 'papaparse'

const DATA = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'data')
const OUT = join(DATA, 'landingCounts.generated.ts')

// Latest dated CSV matching `<prefix>MMDDYYYY[_rN].csv`.
function latestCsv(prefix) {
  const re = new RegExp(`^${prefix}(\\d{2})(\\d{2})(\\d{4})(?:_r(\\d+))?\\.csv$`)
  let best = null
  for (const f of readdirSync(DATA)) {
    const m = f.match(re)
    if (!m) continue
    const key = `${m[3]}${m[1]}${m[2]}${(m[4] ?? '0').padStart(3, '0')}`
    if (!best || key > best.key) best = { key, file: f }
  }
  if (!best) throw new Error(`no ${prefix}*.csv found`)
  return best.file
}

function parseRows(file) {
  const { data } = Papa.parse(readFileSync(join(DATA, file), 'utf8'), {
    header: true,
    skipEmptyLines: true,
  })
  return data
}

const ACTIVE_EXCLUDED_STATUSES = new Set(['deprecated', 'obsolete'])
function countActive(rows) {
  return rows.filter((r) => !ACTIVE_EXCLUDED_STATUSES.has((r.status ?? '').trim().toLowerCase()))
    .length
}

function derive() {
  const algoFile = latestCsv('pqc_complete_algorithm_reference_')
  const timelineFile = latestCsv('timeline_')
  const libraryFile = latestCsv('library_')

  return {
    algoFile,
    timelineFile,
    libraryFile,
    algorithmCount: parseRows(algoFile).length,
    timelineEventCount: countActive(parseRows(timelineFile)),
    libraryCount: countActive(parseRows(libraryFile)),
  }
}

function generate(d) {
  return `// SPDX-License-Identifier: GPL-3.0-only
// GENERATED by scripts/gen-landing-counts.mjs from ${d.algoFile} / ${d.timelineFile} / ${d.libraryFile} — DO NOT EDIT BY HAND.
// Edit the source CSVs and re-run \`npm run gen:landing-counts\` (runs in prebuild).
// These seed LandingView's hero-counter INITIAL state only — see the script's
// own docstring for why they are estimates, not exact counts, and why that's fine.

export const ALGORITHM_COUNT_ESTIMATE = ${d.algorithmCount}
export const TIMELINE_EVENT_COUNT_ESTIMATE = ${d.timelineEventCount}
export const LIBRARY_COUNT_ESTIMATE = ${d.libraryCount}
`
}

const args = process.argv.slice(2)
const derived = derive()
const next = generate(derived)

if (args.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(OUT, 'utf8')
  } catch {
    /* missing → stale */
  }
  if (current !== next) {
    console.error(`✗ ${OUT} is stale vs latest CSVs — run \`npm run gen:landing-counts\``)
    process.exit(1)
  }
  console.log('✓ landing counts up to date')
  process.exit(0)
}

writeFileSync(OUT, next)
console.log(
  `wrote ${OUT} — algorithms ${derived.algorithmCount}, timeline ${derived.timelineEventCount}, library ${derived.libraryCount}`
)
