/**
 * gen-view-source-citations - derive which trusted-source ids each data page cites, from the
 * `trusted_source_id` column of that page's own records (newest dated CSV of each page, active rows
 * only). Emits src/data/generated/viewSourceCitations.generated.ts. The Sources button on a page
 * lists the registry sources named here, so a page lists exactly the sources its records cite and
 * no hand-kept per-page flag can drift from the records.
 *
 *   node scripts/ci/gen-view-source-citations.mjs           # (re)generate
 *   node scripts/ci/gen-view-source-citations.mjs --check   # exit 1 if the committed file is stale
 *
 * The row filters repeat each page loader's own (active rows; published threats; reviewed timeline
 * rows; classified algorithm rows). `src/data/viewSourceCitations.test.ts` compares the result with
 * the sets the real loaders produce, so a filter that drifts fails there.
 * Patents is not listed: patent records carry no trusted_source_id (the issuing authorities are
 * named by the registry's own Patents flag).
 */
import { readFileSync, writeFileSync, readdirSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'
import Papa from 'papaparse'
import prettier from 'prettier'

const DATA = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'src', 'data')
const OUT = join(DATA, 'generated', 'viewSourceCitations.generated.ts')

function latestCsv(prefix) {
  const re = new RegExp(`^${prefix}_(\\d{2})(\\d{2})(\\d{4})(?:_r(\\d+))?\\.csv$`)
  let best = null
  for (const f of readdirSync(DATA)) {
    const m = f.match(re)
    if (!m) continue
    const key = `${m[3]}${m[1]}${m[2]}${(m[4] ?? '0').padStart(3, '0')}`
    if (!best || key > best.key) best = { key, file: f }
  }
  if (!best) throw new Error(`no ${prefix}_*.csv found`)
  return best.file
}

const rowsOf = (file) =>
  Papa.parse(readFileSync(join(DATA, file), 'utf8'), { header: true, skipEmptyLines: true }).data

const isActive = (r) => !r.status || r.status === 'active'
const unreviewed = new Set(
  JSON.parse(readFileSync(join(DATA, 'timelineReviewPolicy.json'), 'utf8')).unreviewedStatuses.map(
    (s) => s.trim().toLowerCase()
  )
)

const VIEWS = {
  Library: { prefix: 'library', keep: isActive },
  Threats: {
    prefix: 'quantum_threats_hsm_industries',
    keep: (r) =>
      !['deprecated', 'obsolete', 'draft'].includes((r.status ?? '').trim().toLowerCase()),
  },
  Compliance: { prefix: 'compliance', keep: isActive },
  Algorithms: {
    prefix: 'pqc_complete_algorithm_reference',
    keep: (r) =>
      r.algorithm?.trim() &&
      r.algorithm_family?.trim() &&
      r.cryptographic_family?.trim() &&
      r.status_tier !== 'placeholder',
  },
  Migrate: { prefix: 'pqc_product_catalog', keep: isActive },
  Timeline: {
    prefix: 'timeline',
    keep: (r) => isActive(r) && !unreviewed.has((r.Status ?? '').trim().toLowerCase()),
  },
  Leaders: { prefix: 'leaders', keep: isActive },
}

function derive() {
  const out = {}
  const files = []
  for (const [view, { prefix, keep }] of Object.entries(VIEWS)) {
    const file = latestCsv(prefix)
    files.push(file)
    const ids = new Set()
    for (const r of rowsOf(file)) {
      const id = (r.trusted_source_id ?? '').trim()
      if (id && keep(r)) ids.add(id)
    }
    out[view] = [...ids].sort()
  }
  return { out, files }
}

function generate({ out, files }) {
  const body = Object.entries(out)
    .map(
      ([view, ids]) =>
        `  ${view}: [\n${ids.map((i) => `    '${i.replace(/'/g, "\\'")}',`).join('\n')}\n  ],`
    )
    .join('\n')
  return `// SPDX-License-Identifier: AGPL-3.0-only
// GENERATED by scripts/ci/gen-view-source-citations.mjs from ${files.join(' / ')} — DO NOT EDIT BY HAND.
// The trusted-source ids each page's active records cite (their \`trusted_source_id\` column).

export type CitedView =
  | 'Library'
  | 'Threats'
  | 'Compliance'
  | 'Algorithms'
  | 'Migrate'
  | 'Timeline'
  | 'Leaders'

export const VIEW_CITED_SOURCE_IDS: Record<CitedView, readonly string[]> = {
${body}
}
`
}

async function main() {
  const check = process.argv.includes('--check')
  const next = await prettier.format(generate(derive()), {
    ...((await prettier.resolveConfig(OUT)) ?? {}),
    filepath: OUT,
  })
  if (check) {
    let current = ''
    try {
      current = readFileSync(OUT, 'utf8')
    } catch {
      // missing counts as stale
    }
    if (current !== next) {
      console.error(
        'src/data/generated/viewSourceCitations.generated.ts is stale. Run: npm run gen:view-source-citations'
      )
      process.exit(1)
    }
    console.log('viewSourceCitations.generated.ts is current')
    return
  }
  writeFileSync(OUT, next)
  console.log('Wrote src/data/generated/viewSourceCitations.generated.ts')
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
