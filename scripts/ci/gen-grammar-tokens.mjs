/**
 * gen-grammar-tokens: write src/styles/grammar-tokens.css from src/styles/grammarTokens.json.
 *
 * The JSON is the one table for the UX grammar's chip-tone colours (a text, fill and border
 * colour per tone, light and dark) and its type scale. The CSS holds them as HSL channel
 * triples (the same form as every other token in index.css), as Tailwind theme colours, and as
 * the named type-style classes. No colour is written by hand anywhere else.
 *
 *   node scripts/ci/gen-grammar-tokens.mjs           # (re)generate
 *   node scripts/ci/gen-grammar-tokens.mjs --check   # exit 1 if the CSS is stale (CI gate)
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import prettier from 'prettier'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const SRC = join(ROOT, 'src', 'styles', 'grammarTokens.json')
const OUT = join(ROOT, 'src', 'styles', 'grammar-tokens.css')

/** `#RRGGBB` to the Hub's channel form `H S% L%` (one decimal, like index.css). */
export function hexToChannels(hex) {
  const m = /^#([0-9a-f]{6})$/i.exec(hex)
  if (!m) throw new Error(`not a #RRGGBB colour: ${hex}`)
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(m[1].slice(i, i + 2), 16) / 255)
  const max = Math.max(r, g, b)
  const min = Math.min(r, g, b)
  const l = (max + min) / 2
  const d = max - min
  let h = 0
  let s = 0
  if (d !== 0) {
    s = d / (1 - Math.abs(2 * l - 1))
    if (max === r) h = ((g - b) / d + (g < b ? 6 : 0)) * 60
    else if (max === g) h = ((b - r) / d + 2) * 60
    else h = ((r - g) / d + 4) * 60
  }
  const n = (v) => String(Math.round(v * 10) / 10)
  return `${n(h)} ${n(s * 100)}% ${n(l * 100)}%`
}

const FONT = {
  display: 'var(--font-display)',
  sans: 'var(--font-sans)',
  mono: 'ui-monospace, SFMono-Regular, Menlo, monospace',
}

export function buildCss(spec) {
  const tokenLines = (mode) =>
    spec.chipTones
      .flatMap((t) => {
        const v = t[mode]
        const border = v.border ?? v.fg
        return [
          `--chip-${t.tone}-fg: ${hexToChannels(v.fg)};`,
          `--chip-${t.tone}-bg: ${hexToChannels(v.bg)};`,
          `--chip-${t.tone}-border: ${hexToChannels(border)};`,
        ]
      })
      .join('\n  ')
  const theme = spec.chipTones
    .flatMap((t) =>
      ['fg', 'bg', 'border'].map(
        (k) => `--color-chip-${t.tone}-${k}: hsl(var(--chip-${t.tone}-${k}));`
      )
    )
    .join('\n  ')
  const styles = Object.entries(spec.typeStyles)
    .map(([name, s]) => {
      const common = [
        `font-family: ${FONT[s.font]};`,
        `font-weight: ${s.weight};`,
        `line-height: ${s.lineHeight};`,
        s.caps ? 'text-transform: uppercase;' : '',
        s.tracking ? `letter-spacing: ${s.tracking};` : '',
      ].filter(Boolean)
      const phone = `font-size: ${s.phone}px;`
      const md =
        s.md !== s.phone
          ? `@media (min-width: 768px) { .type-${name} { font-size: ${s.md}px; } }`
          : ''
      return `.type-${name} {\n    ${common.join('\n    ')}\n    ${phone}\n  }\n  ${md}`
    })
    .join('\n  ')
  return `/* GENERATED by scripts/ci/gen-grammar-tokens.mjs from src/styles/grammarTokens.json. Do not edit.
   Chip-tone colours (light and dark) and the named type styles of the UX grammar. */
:root {
  ${tokenLines('light')}
}

.dark {
  ${tokenLines('dark')}
}

@theme {
  ${theme}
}

@layer components {
  ${styles}
}
`
}

export async function render() {
  const spec = JSON.parse(readFileSync(SRC, 'utf8'))
  const css = buildCss(spec)
  const config = (await prettier.resolveConfig(OUT)) ?? {}
  return prettier.format(css, { ...config, parser: 'css' })
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = await render()
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(OUT, 'utf8')
    } catch {
      /* missing counts as stale */
    }
    if (current !== out) {
      console.error('grammar-tokens.css is stale: run `npm run gen:grammar-tokens`')
      process.exit(1)
    }
    console.log('grammar-tokens.css is current')
  } else {
    writeFileSync(OUT, out)
    console.log(`wrote ${OUT}`)
  }
}
