/**
 * gen-sbom-versions — derive the About page's Software Bill of Materials
 * version column from package.json at build time.
 *
 * WHY THIS EXISTS
 * ---------------
 * SbomSection.tsx used to list ~90 components with HAND-TYPED version strings
 * on the one public page whose entire purpose is saying what this app is
 * built from. On 2026-08-09 eleven of them were wrong in both directions
 * (page behind AND page ahead of package.json); a gate was added
 * (scripts/audit-sbom-versions.ts) that failed CI on every dependabot bump
 * that forgot to edit the page — which was every one of them (PR #624), and
 * one that DID edit it by hand wiped five component names in the process
 * (PR #598). Deriving the column removes the whole class of failure: a
 * dependency bump changes package.json, the next build regenerates this file,
 * and the page can no longer disagree with the lockstep it ships from.
 *
 * WHAT IT DOES
 * ------------
 * src/data/sbomComponents.ts stays the curated, hand-maintained list of WHICH
 * components appear, under which category, with which license / link / note.
 * Every entry that is a direct npm dependency names its package.json key in
 * `pkg`; this script resolves each such key to the exact version package.json
 * pins and emits src/data/sbomVersions.generated.ts with ONLY those entries.
 * Entries with no `pkg` (Rust crates, OpenSSL WASM, the engine bundles, the
 * Web Crypto API) keep their hand-typed `version` text and are not touched.
 *
 * A `pkg` that is not a direct dependency, or whose spec cannot be pinned to
 * an exact version (`file:`, a wide range), is a hard error — the curated
 * list is then wrong about the app and must be edited, not papered over.
 *
 *   node scripts/gen-sbom-versions.mjs           # (re)generate
 *   node scripts/gen-sbom-versions.mjs --check   # exit 1 if stale (CI gate)
 */
import { readFileSync, writeFileSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const COMPONENTS = join(ROOT, 'src', 'data', 'sbomComponents.ts')
const OUT = join(ROOT, 'src', 'data', 'sbomVersions.generated.ts')

/** `^1.2.3` / `~1.2.3` / `1.2.3` -> `1.2.3`. Anything else cannot be pinned. */
function exactVersion(spec) {
  const m = /^[\^~]?(\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?)$/.exec(spec.trim())
  return m ? m[1] : null
}

/**
 * Every package.json key the curated list names — `pkg: 'react'` and
 * `pkg: ['jspdf', 'jspdf-autotable']` alike. A plain scan of the source is
 * enough: the list is data, not code, and its `pkg` values are string
 * literals by construction (the type says so).
 */
function listedPackages() {
  const src = readFileSync(COMPONENTS, 'utf8')
  const keys = new Set()
  for (const m of src.matchAll(/\bpkg:\s*(\[[^\]]*\]|'[^']+')/g)) {
    for (const k of m[1].matchAll(/'([^']+)'/g)) keys.add(k[1])
  }
  return [...keys].sort()
}

function derive() {
  const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'))
  const deps = { ...pkg.dependencies, ...pkg.devDependencies }
  const versions = {}
  const errors = []
  for (const key of listedPackages()) {
    const spec = deps[key]
    if (!spec) {
      errors.push(`${key}: listed in sbomComponents.ts but not a direct dependency in package.json`)
      continue
    }
    const v = exactVersion(spec)
    if (!v) {
      errors.push(`${key}: spec "${spec}" cannot be pinned — give the entry a hand-typed version`)
      continue
    }
    versions[key] = v
  }
  if (errors.length) {
    console.error('✗ SBOM component list disagrees with package.json:')
    for (const e of errors) console.error(`   ${e}`)
    process.exit(1)
  }
  return versions
}

function generate(versions) {
  // Prettier-clean output (single quotes, keys quoted only when not identifiers)
  // so the committed file never trips `npm run format:check`.
  const key = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : `'${k}'`)
  const lines = Object.entries(versions).map(([k, v]) => `  ${key(k)}: '${v}',`)
  return `// SPDX-License-Identifier: GPL-3.0-only
// GENERATED by scripts/gen-sbom-versions.mjs from package.json — DO NOT EDIT BY HAND.
// Bump the dependency and re-run \`npm run gen:sbom-versions\` (runs in prebuild).
// Keys are the package.json names that src/data/sbomComponents.ts lists in \`pkg\`;
// values are the exact versions package.json pins. Nothing else is emitted.

export const SBOM_PACKAGE_VERSIONS: Readonly<Record<string, string>> = {
${lines.join('\n')}
}
`
}

const args = process.argv.slice(2)
const versions = derive()
const next = generate(versions)

if (args.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(OUT, 'utf8')
  } catch {
    /* missing → stale */
  }
  if (current !== next) {
    console.error(`✗ ${OUT} is stale vs package.json — run \`npm run gen:sbom-versions\``)
    process.exit(1)
  }
  console.log('✓ SBOM versions up to date')
  process.exit(0)
}

writeFileSync(OUT, next)
console.log(`wrote ${OUT} — ${Object.keys(versions).length} direct dependencies`)
